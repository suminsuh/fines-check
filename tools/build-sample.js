// Rebuilds prototype/sample-data.js from the five CSVs in the repo root.
// Browsers won't let a page opened from disk read other files on disk, so the
// "Try it with the sample data" button needs the data bundled into a script.
//   node tools/build-sample.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const names = {
  letters: 'fine_letters.csv', log: 'fines_log.csv', portal: 'portal_export.csv',
  vehicles: 'vehicles.csv', roster: 'driver_roster.csv',
};
const files = {};
for (const [k, f] of Object.entries(names)) files[k] = fs.readFileSync(path.join(root, f), 'utf8');

// The portal export has no date of its own. 6 Oct 2026 is the latest date
// anywhere in the sample (last log entry), so treat that as the export day.
const out = '// Generated by tools/build-sample.js. Do not edit by hand.\nwindow.SAMPLE_DATA = ' +
  JSON.stringify({ reportDate: '2026-10-06', names, files }) + ';\n';
fs.writeFileSync(path.join(root, 'prototype', 'sample-data.js'), out);
console.log('Wrote prototype/sample-data.js');
